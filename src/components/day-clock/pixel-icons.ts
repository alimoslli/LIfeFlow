type Paths = { fill: string; d: string }[];
const cache = new Map<string, Paths>();
const norm = (e: string) => e.replace(/️/g, "").trim();

/** The picture's coloured paths (one per colour, merged runs), or null for an emoji we haven't drawn. */
export function pixelPaths(emoji: string): Paths | null {
  const key = OF[norm(emoji)];
  if (!key) return null;
  const hit = cache.get(key);
  if (hit) return hit;
  const by = new Map<string, string>();
  ART[key].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let n = 1;
      while (row[x + n] === ch) n++;
      if (ch !== "." && PAL[ch]) by.set(PAL[ch], `${by.get(PAL[ch]) ?? ""}M${x} ${y}h${n}v1h-${n}z`);
      x += n;
    }
  });
  const paths = [...by].map(([fill, d]) => ({ fill, d }));
  cache.set(key, paths);
  return paths;
}

const escHtml = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c] ?? c);

/** The icon as inline HTML: our pixel picture, or the emoji itself (never a box). */
export function iconHtml(emoji: string, cls = "dc-px"): string {
  const p = pixelPaths(emoji);
  if (!p) return `<span class="${cls} dc-px-emoji">${escHtml(emoji)}</span>`;
  return `<svg class="${cls}" data-icon="${OF[norm(emoji)]}" viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">${p.map((x) => `<path fill="${x.fill}" d="${x.d}"/>`).join("")}</svg>`;
}

const DRAWN = new RegExp(`(${Object.keys(OF).join("|")})️?`, "gu");
/** Every drawn emoji in a piece of (already escaped) HTML text becomes its pixel picture. */
export const pixelize = (html: string) => html.replace(DRAWN, (m) => iconHtml(m));

/** The icon inside an SVG (the wheel): our picture as a nested svg at x, y (its centre) and size, or the emoji as text. */
export function iconSvgInto(parent: Element, emoji: string, cx: number, cy: number, size: number, attrs: Record<string, string> = {}) {
  const NS = "http://www.w3.org/2000/svg";
  const p = pixelPaths(emoji);
  if (!p) {
    const t = document.createElementNS(NS, "text");
    for (const [k, v] of Object.entries({
      x: cx.toFixed(1),
      y: (cy + size * 0.36).toFixed(1),
      "text-anchor": "middle",
      "font-size": (size * 0.9).toFixed(1),
      ...attrs,
    }))
      t.setAttribute(k, v);
    t.textContent = emoji;
    parent.appendChild(t);
    return t;
  }
  const s = document.createElementNS(NS, "svg");
  for (const [k, v] of Object.entries({
    x: (cx - size / 2).toFixed(1),
    y: (cy - size / 2).toFixed(1),
    width: size.toFixed(1),
    height: size.toFixed(1),
    viewBox: "0 0 12 12",
    "shape-rendering": "crispEdges",
    class: "dc-px-svg",
    ...attrs,
  }))
    s.setAttribute(k, v);
  for (const x of p) {
    const path = document.createElementNS(NS, "path");
    path.setAttribute("fill", x.fill);
    path.setAttribute("d", x.d);
    s.appendChild(path);
  }
  parent.appendChild(s);
  return s;
}
