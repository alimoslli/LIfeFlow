import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

/**
 * Compiles skills/<name>/SKILL.md (+ evals.json) into src/server/jarvis/skills/index.generated.ts,
 * so adding a skill is just adding a folder. Run by build and checked by tests (they fail if it's stale).
 */
import type { SkillFile } from "../src/server/jarvis/skills/types";
export type { SkillFile };

export function readSkills(root = join(process.cwd(), "skills")): SkillFile[] {
  return readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(root, d.name, "SKILL.md")))
    .map((d) => {
      const raw = readFileSync(join(root, d.name, "SKILL.md"), "utf8");
      const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw);
      if (!m) throw new Error(`${d.name}/SKILL.md needs a --- front matter block`);
      const meta: Record<string, string> = {};
      for (const line of m[1].split("\n")) {
        const i = line.indexOf(":");
        if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim();
      }
      const list = (k: string) => (meta[k] ? (JSON.parse(meta[k]) as string[]) : []);
      const evalsPath = join(root, d.name, "evals.json");
      return {
        name: meta.name || d.name,
        title: meta.title || d.name,
        description: meta.description || "",
        triggers: list("triggers").map((t) => t.toLowerCase()),
        modules: list("modules"),
        tools: list("tools"),
        body: m[2].trim(),
        evals: existsSync(evalsPath) ? JSON.parse(readFileSync(evalsPath, "utf8")) : [],
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function renderIndex(skills: SkillFile[]) {
  return `// Generated by scripts/build-skills.ts from skills/*/SKILL.md. Do not edit; run \`npm run skills\`.\nimport type { SkillFile } from "./types";\n\nexport const SKILLS: SkillFile[] = ${JSON.stringify(skills, null, 2)};\n`;
}

if (process.argv[1]?.endsWith("build-skills.ts")) {
  const out = join(process.cwd(), "src/server/jarvis/skills/index.generated.ts");
  writeFileSync(out, renderIndex(readSkills()));
  console.log(`Wrote ${readSkills().length} skills.`);
}
